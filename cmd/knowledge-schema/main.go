// knowledge-schema generates the three reviewed initialization scripts from the models.
package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/ccfos/nightingale/v6/models"
	"gorm.io/driver/mysql"
	"gorm.io/driver/postgres"
	"gorm.io/driver/sqlite"
	"gorm.io/gorm"
	"gorm.io/gorm/logger"
)

type capture struct{ statements *[]string }

func (c capture) LogMode(logger.LogLevel) logger.Interface    { return c }
func (capture) Info(context.Context, string, ...interface{})  {}
func (capture) Warn(context.Context, string, ...interface{})  {}
func (capture) Error(context.Context, string, ...interface{}) {}
func (c capture) Trace(_ context.Context, _ time.Time, fc func() (string, int64), _ error) {
	sql, _ := fc()
	if strings.HasPrefix(sql, "CREATE ") {
		*c.statements = append(*c.statements, sql)
	}
}
func main() {
	out := flag.String("out", "doc/sql", "Output directory")
	flag.Parse()
	if err := os.MkdirAll(*out, 0755); err != nil {
		panic(err)
	}
	for _, dialect := range []string{"sqlite", "mysql", "postgres"} {
		var d gorm.Dialector
		switch dialect {
		case "sqlite":
			d = sqlite.Open(":memory:")
		case "mysql":
			d = mysql.New(mysql.Config{DSN: "unused:unused@tcp(127.0.0.1:1)/unused", SkipInitializeWithVersion: true})
		case "postgres":
			d = postgres.New(postgres.Config{DSN: "host=127.0.0.1 port=1 user=unused dbname=unused sslmode=disable"})
		}
		sql := []string{}
		db, err := gorm.Open(d, &gorm.Config{DryRun: true, DisableAutomaticPing: true, Logger: capture{&sql}})
		if err != nil {
			panic(err)
		}
		tables := models.LibraryTables()
		if err = db.Migrator().CreateTable(tables...); err != nil {
			panic(err)
		}
		var b strings.Builder
		b.WriteString("-- Archive knowledge schema. Generated by go run ./cmd/knowledge-schema.\n")
		for _, statement := range sql {
			statement = strings.Replace(statement, "CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
			if dialect != "mysql" {
				statement = strings.Replace(statement, "CREATE UNIQUE INDEX ", "CREATE UNIQUE INDEX IF NOT EXISTS ", 1)
				statement = strings.Replace(statement, "CREATE INDEX ", "CREATE INDEX IF NOT EXISTS ", 1)
			}
			statement = strings.ReplaceAll(statement, "IF NOT EXISTS IF NOT EXISTS", "IF NOT EXISTS")
			statement = strings.ReplaceAll(statement, "NOT NULL NOT NULL", "NOT NULL")
			b.WriteString(statement + ";\n")
		}
		path := filepath.Join(*out, "knowledge-documents."+dialect+".sql")
		if err = os.WriteFile(path, []byte(b.String()), 0644); err != nil {
			panic(err)
		}
		fmt.Println(path)
	}
}
