package opsdemo

import (
	"encoding/json"
	"fmt"
	"net/http"
	"strings"
)

// ScriptedModel exercises the actual HTTP model/tool loop without an external
// provider. It is a fixture, not an evaluation of real model reasoning.
func ScriptedModel(w http.ResponseWriter, r *http.Request) {
	r.Body = http.MaxBytesReader(w, r.Body, 2<<20)
	var request struct {
		Messages []struct {
			Role       string `json:"role"`
			Content    string `json:"content"`
			Name       string `json:"name"`
			ToolCallID string `json:"tool_call_id"`
			ToolCalls  []struct {
				ID       string `json:"id"`
				Function struct {
					Name      string `json:"name"`
					Arguments string `json:"arguments"`
				} `json:"function"`
			} `json:"tool_calls"`
		} `json:"messages"`
	}
	if err := json.NewDecoder(r.Body).Decode(&request); err != nil {
		http.Error(w, "invalid fixture model request", 400)
		return
	}
	for _, message := range request.Messages {
		if message.Role == "system" && (strings.Contains(message.Content, "Create an unverified operations knowledge draft") || strings.Contains(message.Content, "submit_ops_knowledge_draft")) {
			draft := map[string]interface{}{"title": "Scripted source draft (unverified test fixture)", "spec": map[string]interface{}{"summary": "Source-review fixture; operator confirmation is required", "body": "This draft is generated by a deterministic local fixture. Missing information: system and version, actual observations, permitted operations, rollback, business validation and ownership.", "conditions": map[string]string{"environment": "test"}, "test_only": true, "steps": []interface{}{map[string]interface{}{"key": "review", "title": "Review the supplied source", "kind": "manual", "instruction": "An operator must check the selected source and fill the missing applicability and procedure information."}}, "checks": []interface{}{map[string]interface{}{"key": "business", "title": "Operator verifies the actual business result", "kind": "manual", "required": true}}, "escalation": "Hand the unverified draft to the responsible engineer"}}
			raw, _ := json.Marshal(draft)
			w.Header().Set("Content-Type", "application/json")
			_ = json.NewEncoder(w).Encode(map[string]interface{}{"id": "ops-scripted-draft", "object": "chat.completion", "model": "ops-scripted-fixture", "choices": []interface{}{map[string]interface{}{"index": 0, "message": map[string]string{"role": "assistant", "content": string(raw)}, "finish_reason": "stop"}}})
			return
		}
	}
	seen := map[string]bool{}
	last := ""
	lastResult := ""
	names := map[string]string{}
	callArgs := map[string]map[string]interface{}{}
	completed := map[string]bool{}
	for _, m := range request.Messages {
		for _, call := range m.ToolCalls {
			names[call.ID] = call.Function.Name
			var args map[string]interface{}
			_ = json.Unmarshal([]byte(call.Function.Arguments), &args)
			callArgs[call.ID] = args
		}
		if m.Role == "tool" {
			if m.Name == "" {
				m.Name = names[m.ToolCallID]
			}
			seen[m.Name] = true
			last = m.Name
			lastResult = m.Content
			if m.Name == "record_ops_step_result" && !strings.HasPrefix(m.Content, "Error:") && callArgs[m.ToolCallID]["state"] == "completed" {
				key, _ := callArgs[m.ToolCallID]["key"].(string)
				completed[key] = true
			}
		}
	}
	name := ""
	args := map[string]interface{}{}
	content := ""
	switch {
	case !seen["get_ops_context"]:
		name = "get_ops_context"
	case !seen["search_ops_knowledge"]:
		name = "search_ops_knowledge"
	case last == "search_ops_knowledge":
		var matches []struct {
			Applicable bool `json:"applicable"`
			Version    struct {
				ID int64 `json:"id"`
			} `json:"version"`
		}
		if json.Unmarshal([]byte(lastResult), &matches) == nil {
			for _, m := range matches {
				if m.Applicable {
					name = "select_ops_knowledge"
					args["version_id"] = m.Version.ID
					break
				}
			}
		}
		if name == "" {
			content = "No applicable published knowledge. Operator review is required."
		}
	case !completed["storage"] || !completed["queue"]:
		key, query := "storage", "ops_demo_quota_used_ratio"
		if completed["storage"] {
			key, query = "queue", "ops_demo_queue_size"
		}
		var evidence struct {
			ID     int64  `json:"id"`
			Query  string `json:"query"`
			Status string `json:"status"`
		}
		if last == "collect_ops_metric" && json.Unmarshal([]byte(lastResult), &evidence) == nil && evidence.Query == query && evidence.Status == "ok" {
			name = "record_ops_step_result"
			args = map[string]interface{}{"key": key, "state": "completed", "evidence_ids": []int64{evidence.ID}, "note": "Scripted fixture recorded the real scoped metric query"}
		} else {
			name = "collect_ops_metric"
			args = map[string]interface{}{"query": query, "window_seconds": 60}
		}
	case !seen["propose_ops_action"]:
		name = "propose_ops_action"
		args["key"] = "reclaim"
	default:
		content = "Scripted fixture completed evidence collection and prepared a proposal. An operator must review and confirm it; recovery is not claimed."
	}
	message := map[string]interface{}{"role": "assistant", "content": content}
	finish := "stop"
	if name != "" {
		raw, _ := json.Marshal(args)
		message["tool_calls"] = []interface{}{map[string]interface{}{"id": fmt.Sprintf("fixture_%d", len(request.Messages)), "type": "function", "function": map[string]interface{}{"name": name, "arguments": string(raw)}}}
		finish = "tool_calls"
	}
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(map[string]interface{}{"id": "ops-scripted-fixture", "object": "chat.completion", "model": "ops-scripted-fixture", "choices": []interface{}{map[string]interface{}{"index": 0, "message": message, "finish_reason": finish}}, "usage": map[string]int{"prompt_tokens": 1, "completion_tokens": 1, "total_tokens": 2}})
}
