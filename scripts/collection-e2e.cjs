// Run against an isolated, current worktree preview. No login traces or secret output.
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { chromium, expect } = require('../frontend/node_modules/@playwright/test');

async function main() {
  const directory = process.env.N9E_COLLECTION_E2E_INSTANCE;
  const binary = process.env.N9E_TEST_CATEGRAF_BINARY;
  const addressFile = process.env.N9E_TEST_COLLECTION_PREVIEW_FIXTURE_FILE;
  if (!directory || !binary || !addressFile) throw new Error('Provide the private preview directory, patched collector binary and fixture address file');
  const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json')));
  if (manifest.role !== 'development' || manifest.frontend.kind !== 'in-tree') throw new Error('A development preview with in-tree assets is required');
  if (!manifest.lanHost) throw new Error('Configure the development preview LAN address before running collection E2E');
  const base = `http://${manifest.lanHost}:${manifest.port}`;
  const credentials = JSON.parse(fs.readFileSync(path.join(directory, 'credentials.json')));
  const writer = JSON.parse(fs.readFileSync(path.join(directory, 'collector.json')));
  const address = fs.readFileSync(addressFile, 'utf8').trim();
  const [host, portText] = address.split(':');
  const port = Number(portText);
  const artifacts = path.join(directory, 'collection-e2e');
  fs.mkdirSync(artifacts, { recursive: true, mode: 0o700 });
  const browser = await chromium.launch({ headless: true });
  let collectorProcess;
  const report = { baseURL: base, buildId: manifest.buildId, source: manifest.source, checks: [], screenshots: [], deviceId: '', collectorId: '' };
  try {
    const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (e) => { errors.push(e.stack || e.message); console.error('Browser page error:', e.stack || e.message); });
    const info = await (await context.request.get(base + '/__preview/info')).json();
    expect(info.buildId).toBe(manifest.buildId); expect(info.ready).toBe(true);
    await page.goto(base + '/login');
    await page.locator('#username').fill(credentials.username);
    await page.locator('#password').fill(credentials.password);
    await page.locator('button.ant-btn-primary').click();
    await page.waitForURL((u) => !u.pathname.startsWith('/login'));
    const token = await page.evaluate(() => localStorage.getItem('access_token'));
    if (!token) throw new Error('Login did not produce a session');
    const api = async (resource, method = 'GET', data, extra = {}) => {
      const response = await context.request.fetch(base + '/api/n9e/' + resource, { method, data, headers: { Authorization: `Bearer ${token}`, ...extra } });
      const body = await response.json();
      if (!response.ok() || body.err) throw new Error(`${method} ${resource}: ${response.status()} ${body.err || 'request failed'}`);
      return body.dat;
    };
    const groups = await api('busi-groups');
    let group = groups.find((g) => g.name === 'SNMP fixture acceptance');
    if (!group) {
      const teams = await api('user-groups');
      if (!teams.length) throw new Error('Preview requires an owner team');
      const id = await api('busi-groups', 'POST', { name: 'SNMP fixture acceptance', members: [{ user_group_id: teams[0].id, perm_flag: 'rw' }] });
      group = { id, name: 'SNMP fixture acceptance' };
    }
    const datasources = await api('datasource/brief');
    const datasource = datasources.find((d) => d.identifier === 'preview-shared-prometheus') || datasources.find((d) => d.plugin_type === 'prometheus');
    if (!datasource) throw new Error('Disposable preview datasource missing');
    await page.goto(base + '/targets?ids=' + group.id + '&isLeaf=true');
    await page.getByRole('button', { name: /采集管理|Collection settings/ }).click();
    await page.getByRole('button', { name: /登记采集器|Register collector/ }).click();
    const registration = page.locator('.ant-modal-content').last();
    const collectorName = 'SNMP fixture collector ' + manifest.buildId.slice(-8);
    await registration.locator('#name').fill(collectorName);
    await registration.locator('#agent_ident').fill('snmp-fixture-' + manifest.buildId.slice(-8));
    await registration.locator('#writer_user').fill(writer.username);
    await registration.locator('#group_ids').fill(String(group.id));
    await registration.locator('#datasource_id').fill(String(datasource.id));
    const registered = page.waitForResponse((r) => r.url().endsWith('/collection/collectors') && r.request().method() === 'POST');
    await registration.locator('.ant-modal-footer .ant-btn-primary').click();
    const registeredBody = await (await registered).json();
    if (registeredBody.err) throw new Error('Collector registration failed: ' + registeredBody.err);
    const collector = registeredBody.dat.collector;
    const configToken = registeredBody.dat.secret;
    report.collectorId = collector.id;
    expect(configToken.length).toBeGreaterThanOrEqual(32);
    await page.locator('.ant-modal-content').last().locator('.ant-modal-footer .ant-btn-primary').click();
    await page.locator('.ant-drawer-close').last().click();
    report.checks.push('collector registered through UI; one-time configuration token returned');

    const configDirectory = path.join(artifacts, 'categraf-conf');
    fs.mkdirSync(path.join(configDirectory, 'input.system'), { recursive: true, mode: 0o700 });
    const quote = JSON.stringify;
    fs.writeFileSync(path.join(configDirectory, 'config.toml'), `[global]\nhostname = ${quote('snmp-fixture-' + manifest.buildId.slice(-8))}\ninterval = 1\nproviders = ["local", "http"]\nprint_configs = false\n[log]\nfile_name = "stdout"\n[http_provider]\nremote_url = ${quote(`http://127.0.0.1:${manifest.backendPort}/v1/n9e/collection/configs`)}\nbasic_auth_user = ${quote(collector.id)}\nbasic_auth_pass = ${quote(configToken)}\ntimeout = 2\nreload_interval = 1\n[writer_opt]\nbatch = 1000\nchan_size = 10000\n[[writers]]\nurl = ${quote(`http://127.0.0.1:${manifest.backendPort}/prometheus/v1/write`)}\nbasic_auth_user = ${quote(writer.username)}\nbasic_auth_pass = ${quote(writer.password)}\ntimeout = 5000\n[http]\nenable = false\n[heartbeat]\nenable = false\n[ibex]\nenable = false\n`, { mode: 0o600 });
    fs.writeFileSync(path.join(configDirectory, 'input.system/system.toml'), 'interval = 1\n', { mode: 0o600 });
    const collectorLog = fs.openSync(path.join(artifacts, 'categraf.log'), 'w', 0o600);
    collectorProcess = spawn(binary, ['-configs', configDirectory], { stdio: ['ignore', collectorLog, collectorLog] });
    fs.closeSync(collectorLog);
    collectorProcess.on('error', () => {});
    await page.getByRole('button', { name: /新增采集设备|Add collection device/ }).click();
    const editor = page.getByRole('dialog', { name: /^(新增采集设备|Add collection device)$/ });
    const ident = 'snmp-fixture-' + manifest.buildId;
    await editor.locator('#name').fill('Windows SNMP fixture');
    await editor.locator('#address').fill(host);
    await editor.locator('#port').fill(String(port));
    await editor.locator('#ident').fill(ident);
    const select = async (id, text) => { await editor.locator('.ant-select-selector').filter({ has: page.locator('#' + id) }).click(); await page.locator('.ant-select-dropdown:visible .ant-select-item-option').filter({ hasText: text }).last().click(); };
    await select('group_id', group.name);
    await select('collector_id', collectorName);
    await editor.locator('button').filter({ hasText: /新增凭据|New credential/ }).click();
    const credentialEditor = page.getByRole('dialog', { name: /^(新增凭据|New credential)$/ });
    await credentialEditor.locator('#name').fill('Synthetic fixture credential');
    await credentialEditor.locator('#community').fill('fixture-community');
    await credentialEditor.locator('.ant-modal-footer .ant-btn-primary').click();
    await expect(credentialEditor).not.toBeVisible();
    await select('interval_seconds', '15');
    const probeCreated = page.waitForResponse((r) => r.url().endsWith('/collection/probes') && r.request().method() === 'POST');
    await editor.getByRole('button', { name: /由采集器测试连接|Test from collector/ }).click();
    const probeBody = await (await probeCreated).json();
    if (probeBody.err) throw new Error('Probe creation failed: ' + probeBody.err);
    const probeId = probeBody.dat.id;
    await expect.poll(async () => (await api('collection/probes/' + probeId)).result, { timeout: 90000 }).toBe('passed');
    const beforeSave = await api('targets?query=' + encodeURIComponent(ident));
    expect(beforeSave.list).toHaveLength(0);
    report.checks.push('collector-side probe passed without registering a Target');
    const saved = page.waitForResponse((r) => r.url().endsWith('/collection/devices') && r.request().method() === 'POST');
    await editor.getByRole('button', { name: /^(保存|Save)$/ }).click();
    const savedBody = await (await saved).json();
    if (savedBody.err) throw new Error('Device save failed: ' + savedBody.err);
    let device = savedBody.dat;
    report.deviceId = device.id;
    expect(device.collection.health).not.toBe('healthy');
    const immediately = await api('targets?query=' + encodeURIComponent(ident));
    expect(immediately.list.some((d) => d.collection?.device_id === device.id)).toBe(true);
    await expect.poll(async () => (await api('collection/devices/' + device.id)).collection.health, { timeout: 90000 }).toBe('healthy');
    device = await api('collection/devices/' + device.id);
    expect(device.collection.cpu_percent).toBe(37.5);
    expect(device.collection.memory_percent).toBe(25);
    expect(device.collection.counter_bits).toBe(32);
    await expect.poll(async () => {
      const data = await api(`collection/devices/${device.id}/metrics`);
      return ['cpu', 'memory', 'disk', 'network_in', 'network_out'].every((key) => data.metrics[key].some((s) => s.values.length > 0));
    }, { timeout: 90000 }).toBe(true);
    await page.locator('.ant-drawer-content').last().getByRole('button', { name: /^(刷新|Refresh)$/ }).click();
    await expect(page.locator('.ant-drawer-content').last().locator('canvas').first()).toBeVisible();
    const screenshot = path.join(artifacts, 'device-healthy.png');
    await page.screenshot({ path: screenshot, fullPage: true }); report.screenshots.push(screenshot);
    report.checks.push('immediate Target registration; current-revision CPU 37.5%, memory 25%, disk and 32-bit fallback interface charts');
    const linux = await (await context.request.get(manifest.prometheusURL + '/api/v1/query', { params: { query: 'system_uptime{ident=' + JSON.stringify('snmp-fixture-' + manifest.buildId.slice(-8)) + '}' } })).json();
    expect(linux.status).toBe('success'); expect(linux.data.result.length).toBeGreaterThan(0); report.checks.push('local Linux system metrics continue through the same validated Center writer');

    const detail = page.locator('.ant-drawer-content').last();
    await detail.getByRole('button', { name: /^(编辑|Edit)$/ }).click();
    const edit = page.locator('.ant-modal-content').last();
    const revision = device.collection.revision;
    const changed = { name: 'Concurrent name change', address: device.address, port: device.port, ident: device.ident, group_id: device.group_id, collector_id: device.collector_id, credential_id: device.credential_id, template_version_id: device.template_version_id, protocol: device.protocol, interval_seconds: device.interval_seconds, timeout_seconds: device.timeout_seconds, retries: device.retries, labels: device.labels, cmdb_id: device.cmdb_id, enabled: device.enabled, record_version: device.record_version };
    await api('collection/devices/' + device.id, 'PUT', changed);
    await edit.locator('#name').fill('Retained conflicting form');
    await edit.getByRole('button', { name: /^(保存|Save)$/ }).click();
    await expect(edit.locator('.ant-alert-error')).toBeVisible();
    await expect(edit.locator('#name')).toHaveValue('Retained conflicting form');
    await edit.getByRole('button', { name: /^(取消|Cancel)$/ }).click();
    device = await api('collection/devices/' + device.id);
    expect(device.collection.revision).toBe(revision);
    report.checks.push('optimistic conflict retains form input; metadata rename preserves device ID and revision');
    await detail.getByRole('button', { name: /^(刷新|Refresh)$/ }).click();
    await expect(detail).toContainText('Concurrent name change');
    await detail.getByRole('button', { name: /^(停用|Disable)$/ }).click();
    await expect.poll(async () => (await api('collection/devices/' + device.id)).collection.configuration_state).toBe('withdraw_pending');
    const force = await context.request.delete(base + '/api/n9e/targets', { headers: { Authorization: `Bearer ${token}` }, data: { idents: [ident], force: true } });
    const forceBody = await force.json(); expect(Boolean(forceBody.err)).toBe(true);
    await expect.poll(async () => (await api('collection/devices/' + device.id)).collection.health, { timeout: 130000 }).toBe('disabled');
    await detail.getByRole('button', { name: /^(刷新|Refresh)$/ }).click();
    await detail.getByRole('button', { name: /^(启用|Enable)$/ }).click();
    await expect.poll(async () => (await api('collection/devices/' + device.id)).collection.health, { timeout: 90000 }).toBe('healthy');
    device = await api('collection/devices/' + device.id); expect(device.collection.revision).not.toBe(revision);
    report.checks.push('disable observed after quiet window; native force deletion blocked; re-enable produces a fresh revision');
    await detail.getByRole('button', { name: /^(删除|Delete)$/ }).click();
    await page.locator('.ant-modal-confirm .ant-btn-primary').click();
    await expect.poll(async () => (await api('targets?query=' + encodeURIComponent(ident))).list.length).toBe(0);
    await expect.poll(async () => (await api('collection/devices/' + device.id)).collection.configuration_state, { timeout: 130000 }).toBe('withdraw_observed');
    await expect.poll(async () => (await api('collection/probes/' + probeId)).state, { timeout: 130000 }).toBe('cleaned');
    const audit = await api('collection/audits?object_id=' + device.id); expect(audit.length).toBeGreaterThanOrEqual(4);
    expect(JSON.stringify(audit)).not.toContain('fixture-community');
    report.checks.push('soft deletion removes the default Target row; device withdrawal and probe cleanup observed; metadata audit contains no community');
    expect(errors).toEqual([]);
    report.checks.push('no browser page errors');
    fs.writeFileSync(path.join(artifacts, 'result.json'), JSON.stringify(report, null, 2), { mode: 0o600 });
    console.log(JSON.stringify({ buildId: report.buildId, checks: report.checks, report: path.join(artifacts, 'result.json') }, null, 2));
  } finally {
    if (collectorProcess) { collectorProcess.kill('SIGTERM'); await Promise.race([new Promise((r) => collectorProcess.once('exit', r)), new Promise((r) => setTimeout(r, 10000))]); if (collectorProcess.exitCode === null) collectorProcess.kill('SIGKILL'); }
    await browser.close();
  }
}
main().catch((e) => { console.error(e.message); process.exitCode = 1; });
